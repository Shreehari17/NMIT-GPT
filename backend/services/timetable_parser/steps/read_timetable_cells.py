"""Read extracted timetable cells using local Ollama Qwen2.5-VL.

Run from NMIT-GPT project root:

  python experiments/qwen_timetable/read_timetable_cells.py 7A --limit 5
  python experiments/qwen_timetable/read_timetable_cells.py 7A

Requires:
  - Ollama running locally
  - ollama pull qwen2.5vl:3b
  - cells_7A/cells.csv generated by extract_timetable_cells.py

Does not modify FastAPI, Supabase, or production data.
"""

import argparse
import base64
import csv
import hashlib
import json
import time
import urllib.error
import urllib.request
from pathlib import Path

MODEL = "qwen2.5vl:3b"
OLLAMA_URL = "http://127.0.0.1:11434"
BASE = Path(__file__).resolve().parent

TIME_SLOTS = [
    ("09:00", "09:55"),
    ("09:55", "10:05"),
    ("10:05", "11:00"),
    ("11:00", "11:55"),
    ("11:55", "12:35"),
    ("12:35", "13:30"),
    ("13:30", "14:25"),
    ("14:25", "15:20"),
    ("15:20", "16:15"),
]

PROMPT = """
You are performing precise OCR on ONE cropped college
timetable cell.

Your ONLY job is to transcribe the text visible in the image.

Rules:
- Copy the characters exactly as shown.
- Preserve subject codes, numbers, slashes and hyphens.
- Preserve LAB, Library, Mentoring and activity names.
- Do not guess missing or unclear characters.
- Do not add a subject name that isn't visible.
- Do not invent time slots, dates, or other cells.
- If the cell is blank, return an empty string.
- If there are multiple lines, combine them with spaces.
- If text is partly unreadable, set uncertain to true.
- Return ONLY a JSON object with these two fields:

{
  "text": "exact visible text",
  "uncertain": false
}
"""


def request_json(url, payload=None, timeout=180):
    data = None

    if payload is not None:
        data = json.dumps(payload).encode("utf-8")

    request = urllib.request.Request(
        url,
        data=data,
        headers={"Content-Type": "application/json"},
        method="POST" if payload is not None else "GET",
    )

    with urllib.request.urlopen(
        request,
        timeout=timeout,
    ) as response:
        return json.loads(response.read().decode("utf-8"))


def check_ollama():
    try:
        result = request_json(
            f"{OLLAMA_URL}/api/tags",
            timeout=10,
        )
    except Exception as exc:
        raise RuntimeError(
            "Cannot connect to Ollama. Run 'ollama serve' "
            "or open the Ollama app."
        ) from exc

    models = [
        item.get("name", "")
        for item in result.get("models", [])
    ]

    if MODEL not in models:
        raise RuntimeError(
            f"Model {MODEL} not found. "
            f"Installed models: {models}"
        )

    print(f"Connected to Ollama: {MODEL}", flush=True)


def image_hash(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def read_image(path):
    encoded_image = base64.b64encode(
        path.read_bytes()
    ).decode("ascii")

    payload = {
        "model": MODEL,
        "stream": False,
        "format": "json",
        "think": False,
        "messages": [
            {
                "role": "user",
                "content": PROMPT,
                "images": [encoded_image],
            }
        ],
        "options": {
            "temperature": 0,
            "num_ctx": 4096,
            "num_predict": 160,
        },
    }

    response = request_json(
        f"{OLLAMA_URL}/api/chat",
        payload=payload,
        timeout=180,
    )

    content = response.get(
        "message", {}
    ).get("content", "").strip()

    if content.startswith("```"):
        content = content.split("\n", 1)[-1]
        content = content.rsplit("```", 1)[0].strip()

    try:
        parsed = json.loads(content)
    except json.JSONDecodeError:
        return {
            "text": content,
            "uncertain": True,
            "reason": "Model did not return valid JSON",
        }

    if not isinstance(parsed, dict):
        return {
            "text": str(parsed),
            "uncertain": True,
            "reason": "Unexpected response structure",
        }

    recognized = parsed.get("text", "")

    if recognized is None:
        recognized = ""

    if not isinstance(recognized, str):
        recognized = str(recognized)

    return {
        "text": " ".join(recognized.split()),
        "uncertain": parsed.get("uncertain") is not False,
        "reason": "",
    }


def read_with_retries(path):
    error = None

    for attempt in range(2):
        try:
            return read_image(path)
        except Exception as exc:
            error = exc

            print(
                f"  Attempt {attempt + 1} failed: {exc}",
                flush=True,
            )

            if attempt == 0:
                time.sleep(2)

    return {
        "text": "",
        "uncertain": True,
        "reason": f"Ollama error: {error}",
    }


def is_true(value):
    return str(value).strip().lower() == "true"


def is_vertical_fragment(row):
    """Merged vertical labels require separate review.

    Do not trust isolated letters like L, U, N, C, H
    as independent subjects.
    """
    same_slot = (
        int(row["first_slot"]) ==
        int(row["last_slot"])
    )

    merged_above = is_true(
        row.get("continues_from_previous_day", "")
    )

    merged_below = is_true(
        row.get("continues_into_next_day", "")
    )

    return same_slot and (
        merged_above or merged_below
    )


def load_cache(path):
    if not path.exists():
        return {}

    try:
        cache = json.loads(path.read_text())
        return cache if isinstance(cache, dict) else {}
    except (json.JSONDecodeError, OSError):
        return {}


def save_json(path, obj):
    temporary = path.with_suffix(path.suffix + ".tmp")

    temporary.write_text(
        json.dumps(obj, indent=2, ensure_ascii=False)
    )

    temporary.replace(path)


def build_timetable(records):
    days = {}

    for record in records:
        day = record["day"]

        if day not in days:
            days[day] = [
                {
                    "slot": index + 1,
                    "start_time": start,
                    "end_time": end,
                    "text": None,
                    "status": "not_processed",
                    "source_image": None,
                }
                for index, (start, end)
                in enumerate(TIME_SLOTS)
            ]

        for slot_number in range(
            record["first_slot"],
            record["last_slot"] + 1,
        ):
            slot = days[day][slot_number - 1]

            slot["text"] = (
                record["text"]
                if record["text"] != ""
                else None
            )

            slot["status"] = record["status"]
            slot["source_image"] = record["image"]

    return days


def main():
    parser = argparse.ArgumentParser()

    parser.add_argument(
        "timetable",
        help="PDF stem, e.g. 7A or 6A",
    )

    parser.add_argument(
        "--limit",
        type=int,
        default=None,
        help="Process only the first N entries",
    )

    args = parser.parse_args()

    folder = BASE / f"cells_{args.timetable}"

    csv_path = folder / "cells.csv"
    cache_path = folder / "ocr_cache.json"
    output_path = folder / f"timetable_{args.timetable}.json"
    review_path = folder / "ocr_review.json"

    if not csv_path.exists():
        raise FileNotFoundError(
            f"Missing {csv_path}. "
            "Run extract_timetable_cells.py first."
        )

    with csv_path.open(newline="") as f:
        all_rows = list(csv.DictReader(f))

    if not all_rows:
        raise RuntimeError("cells.csv contains no rows")

    selected_rows = (
        all_rows[:args.limit]
        if args.limit is not None
        else all_rows
    )

    check_ollama()

    cache = load_cache(cache_path)
    records = []

    print(
        f"\nProcessing {len(selected_rows)} of "
        f"{len(all_rows)} cells\n",
        flush=True,
    )

    for index, row in enumerate(selected_rows, 1):
        path = folder / row["image"]

        if not path.exists():
            raise FileNotFoundError(
                f"Cell image missing: {path}"
            )

        digest = image_hash(path)
        cache_key = (
            f"{MODEL}:{row['image']}:{digest}"
        )

        first_slot = int(row["first_slot"])
        last_slot = int(row["last_slot"])

        print(
            f"[{index}/{len(selected_rows)}] "
            f"{row['day']} slots "
            f"{first_slot}-{last_slot}",
            flush=True,
        )

        if is_vertical_fragment(row):
            result = {
                "text": "",
                "uncertain": True,
                "reason": (
                    "Potential vertically merged cell; "
                    "requires separate recognition"
                ),
            }

            status = "vertical_merge_review"

            print(
                "  Skipped vertically merged fragment",
                flush=True,
            )

        elif cache_key in cache:
            result = cache[cache_key]

            status = (
                "needs_review"
                if result.get("uncertain")
                else "recognized"
            )

            print(
                f"  Cached: {result.get('text', '')}",
                flush=True,
            )

        else:
            result = read_with_retries(path)

            # Save progress immediately after each OCR call.
            cache[cache_key] = result
            save_json(cache_path, cache)

            status = (
                "needs_review"
                if result.get("uncertain")
                or not result.get("text")
                else "recognized"
            )

            print(
                f"  OCR: {result.get('text', '')!r}",
                flush=True,
            )

        records.append({
            "day": row["day"],
            "first_slot": first_slot,
            "last_slot": last_slot,
            "image": row["image"],
            "text": result.get("text", ""),
            "status": status,
            "uncertain": result.get("uncertain", True),
            "reason": result.get("reason", ""),
        })

        # Save updated results after each entry.
        data = {
            "timetable": args.timetable,
            "model": MODEL,
            "processed_cells": len(records),
            "total_cells": len(all_rows),
            "complete": len(records) == len(all_rows),
            "time_slots": TIME_SLOTS,
            "days": build_timetable(records),
            "cells": records,
        }

        save_json(output_path, data)

        review_items = [
            item for item in records
            if item["status"] != "recognized"
        ]

        save_json(review_path, review_items)

    print("\nFinished current run!", flush=True)

    print(
        f"JSON: {output_path}",
        flush=True,
    )

    print(
        f"Review: {review_path}",
        flush=True,
    )

    print(
        f"Cached results: {cache_path}",
        flush=True,
    )

    print(
        "\nIMPORTANT: OCR results require validation "
        "against the source PDF before production use.",
        flush=True,
    )


if __name__ == "__main__":
    main()
